import type { FactorReport } from '../services/api';
import type { BacktestResult } from '../types';

type Hold = { totalReturn: number | null; finalCapital: number | null };

function pct(v: number | null | undefined, digits = 2): string {
  if (v == null) return '—';
  return `${(v * 100).toFixed(digits)}%`;
}

function num(v: number | null | undefined, digits = 2): string {
  if (v == null) return '—';
  return v.toFixed(digits);
}

/** Investor-ready Markdown tearsheet from a single backtest. */
export function tearsheetMarkdown(
  result: BacktestResult,
  opts?: {
    buyHold?: Hold;
    vsHold?: number | null;
    factors?: FactorReport | null;
    multiFactors?: FactorReport[] | null;
  },
): string {
  const m = result.metrics;
  const risk = result.risk;
  const lines: string[] = [
    `# Quantify tearsheet · #${result.id}`,
    '',
    `**Strategy:** ${result.strategy_description}`,
    `**Dataset:** ${result.dataset_name}`,
    `**Side:** ${result.strategy.side ?? 'long'} · **Created:** ${result.created_at?.slice(0, 19) ?? '—'}`,
    '',
    '## Performance',
    '',
    `| Metric | Value |`,
    `| --- | --- |`,
    `| Total return | ${pct(m.total_return)} |`,
    `| Buy & hold | ${pct(opts?.buyHold?.totalReturn)} |`,
    `| vs buy & hold | ${pct(opts?.vsHold)} |`,
    `| CAGR | ${pct(m.cagr)} |`,
    `| Sharpe | ${num(m.sharpe_ratio)} |`,
    `| Sortino | ${num(m.sortino_ratio)} |`,
    `| Max drawdown | ${pct(m.max_drawdown)} |`,
    `| Vol (ann.) | ${pct(m.annualized_volatility)} |`,
    `| Win rate | ${pct(m.win_rate)} |`,
    `| Trades | ${m.number_of_trades} |`,
    `| Final capital | ${m.final_capital == null ? '—' : `$${Math.round(m.final_capital).toLocaleString()}`} |`,
    '',
  ];

  if (risk?.tails) {
    lines.push('## Tail risk', '');
    lines.push('| Confidence | VaR | ES |');
    lines.push('| --- | --- | --- |');
    for (const [a, t] of Object.entries(risk.tails)) {
      lines.push(`| ${a} | ${t.var_pct == null ? '—' : `${t.var_pct}%`} | ${t.es_pct == null ? '—' : `${t.es_pct}%`} |`);
    }
    if (risk.vol_annual != null) lines.push('', `Annualized vol (from equity): **${pct(risk.vol_annual)}**`);
    lines.push('');
  }

  if (result.verdict) {
    lines.push(
      '## Verdict',
      '',
      `**Grade:** ${result.verdict.grade.replace(/_/g, ' ')} · **Score:** ${result.verdict.score}/100`,
      '',
      `_${result.verdict.headline}_`,
      '',
    );
    for (const c of result.verdict.checks) {
      lines.push(`- **${c.label}** (${c.status}): ${c.detail}`);
    }
    lines.push('');
  }

  const factorRows =
    opts?.multiFactors?.length
      ? opts.multiFactors
      : opts?.factors?.beta != null
        ? [opts.factors]
        : [];
  if (factorRows.length) {
    lines.push('## Factor exposure', '', `| Benchmark | Beta | Alpha (ann.) | R² |`, `| --- | --- | --- | --- |`);
    for (const f of factorRows) {
      lines.push(
        `| ${f.benchmark} | ${num(f.beta)} | ${pct(f.alpha_annual)} | ${num(f.r2)} |`,
      );
    }
    lines.push('');
  }

  if (result.market) {
    lines.push(
      '## vs same-asset hold',
      '',
      `- Beta ${num(result.market.beta)} · Alpha (ann.) ${pct(result.market.alpha_annual)}`,
      `- Up capture ${pct(result.market.up_capture)} · Down capture ${pct(result.market.down_capture)}`,
      `- ${result.market.headline}`,
      '',
    );
  }

  lines.push('---', '', `_Generated by Quantify · execution: ${result.execution_convention ?? 'next-open'}_`, '');
  return lines.join('\n');
}

export function duelTearsheetMarkdown(a: BacktestResult, b: BacktestResult, aWins: number, bWins: number, n: number): string {
  return [
    `# Quantify duel · #${a.id} vs #${b.id}`,
    '',
    aWins === bWins
      ? `Split: each wins ${aWins}/${n} measures.`
      : `#${aWins > bWins ? a.id : b.id} wins ${Math.max(aWins, bWins)}/${n} measures.`,
    '',
    `## A · #${a.id}`,
    a.strategy_description,
    `Return ${pct(a.metrics.total_return)} · Sharpe ${num(a.metrics.sharpe_ratio)} · DD ${pct(a.metrics.max_drawdown)}`,
    '',
    `## B · #${b.id}`,
    b.strategy_description,
    `Return ${pct(b.metrics.total_return)} · Sharpe ${num(b.metrics.sharpe_ratio)} · DD ${pct(b.metrics.max_drawdown)}`,
    '',
  ].join('\n');
}
